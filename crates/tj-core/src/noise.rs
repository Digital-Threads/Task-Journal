//! Machine text: what Claude Code and the tools produce, never reasoning.
//! A raw tool call, a compaction summary or a harness notification once got
//! filed as a decision or a rejection; packs, recall, the classifier and the
//! `cleanup-noise` command all tell it apart here, the same way.

/// Why `text` is machine output rather than reasoning, or `None` when it
/// reads as reasoning. Conservative: only shapes no person writes.
pub fn machine_text(text: &str) -> Option<&'static str> {
    let t = text.trim_start();

    let summary = [
        "This session is being continued from a previous conversation",
        "Conversation compacted at",
        "[Conversation compacted",
        "Caveat: The messages below were generated by the user",
    ];
    if summary.iter().any(|p| t.starts_with(p)) {
        return Some("compaction summary");
    }

    let tags = [
        "<task-notification",
        "<system-reminder",
        "<command-name>",
        "<command-message>",
        "<local-command-",
        "<bash-input>",
        "<bash-stdout>",
    ];
    if tags.iter().any(|p| t.starts_with(p)) {
        return Some("harness notification");
    }

    if is_tool_payload(t) {
        return Some("raw tool call");
    }

    if t.starts_with(CLEANUP_PREFIX) {
        return Some("journal cleanup");
    }

    None
}

/// How the correction `cleanup-noise` writes begins: the journal's own
/// bookkeeping, kept out of packs like the rest of this module's text.
pub const CLEANUP_PREFIX: &str = "[cleanup-noise]";

/// `Bash: {"command": …}` or `mcp__server__tool: {…}`: how a hook renders a
/// tool call — the tool's name, a colon, then its JSON input.
fn is_tool_payload(t: &str) -> bool {
    let Some((name, rest)) = t.split_once(": ") else {
        return false;
    };
    let is_name = !name.is_empty()
        && name.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');

    is_name && (rest.starts_with('{') || rest.starts_with('['))
}

#[cfg(test)]
mod tests {
    use super::machine_text;

    #[test]
    fn tool_calls_summaries_and_notifications_are_machine_text() {
        let cases = [
            (r#"Bash: {"command":"git push"} → {"stdout":""}"#, "raw tool call"),
            (r#"Edit: {"file_path":"/x/y.rs","old_string":"a"}"#, "raw tool call"),
            (r#"mcp__plugin_context-mode_context-mode__ctx_execute: {"code":"x"}"#, "raw tool call"),
            (
                "This session is being continued from a previous conversation that ran out of context.",
                "compaction summary",
            ),
            ("Conversation compacted at 2026-06-07T11:47:33Z; …", "compaction summary"),
            ("  [Conversation compacted]", "compaction summary"),
            ("<task-notification> <task-id>wl08</task-id>", "harness notification"),
            ("<system-reminder>Whenever you read a file", "harness notification"),
            ("[cleanup-noise] not a rejection: raw tool call", "journal cleanup"),
        ];

        for (text, why) in cases {
            assert_eq!(machine_text(text), Some(why), "{text}");
        }
    }

    #[test]
    fn reasoning_is_not_machine_text() {
        for text in [
            "Use axum for the server because it has better middleware.",
            "Rejected: per-stage sessions lose accumulated context.",
            "Отклонён chown -R www-data public в Dockerfile: он делает веб-корень записываемым.",
            "Note: the config {a: 1} is read once at start.",
            "",
        ] {
            assert_eq!(machine_text(text), None, "{text}");
        }
    }
}
